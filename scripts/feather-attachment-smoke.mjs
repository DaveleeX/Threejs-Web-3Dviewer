import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('http://127.0.0.1:5173/?showcase=materials&tier=low');
  const result = await page.evaluate(async () => {
    const THREE = await import('/node_modules/three/build/three.module.js');
    const { FeatherEffect } = await import('/src/effects/FeatherEffect.ts');
    const { EffectHost } = await import('/src/effects/EffectHost.ts');
    const scene = new THREE.Scene(), source = new THREE.Mesh(new THREE.SphereGeometry(1, 12, 8), new THREE.MeshStandardMaterial());
    scene.add(source); source.position.set(3, 2, -1); source.scale.set(2, 0.7, 1.3); source.rotation.y = 0.7;
    const originalMaterial = source.material, originalGeometry = source.geometry;
    const host = new EffectHost(scene);
    host.add(new FeatherEffect([source], { count: 300, look: 'gorget', direction: [0, -1, 0] }));
    const child = source.children[0]; scene.updateMatrixWorld(true);
    const atMountIdentity = child.matrixWorld.equals(new THREE.Matrix4());
    const matrixError = Math.max(...child.matrixWorld.elements.map((v, i) => Math.abs(v - new THREE.Matrix4().elements[i])));
    const attributes = ['aRoot', 'aHinge', 'aData', 'aIriN', 'aBase', 'aTip', 'aIri', 'aIri2'].every(a => child.geometry.hasAttribute(a));
    const finite = Object.values(child.geometry.attributes).every(a => [...a.array].every(Number.isFinite));
    const geometry = child.geometry;
    let disposed = false; geometry.addEventListener('dispose', () => { disposed = true; });
    const initialRoot = geometry.getAttribute('aRoot').array.slice(0, 30);
    source.position.x += 2; scene.updateMatrixWorld(true);
    const follows = Math.abs(child.matrixWorld.elements[12] - 2) < 1e-6;
    for (let i = 0; i < 60; i++) host.update(1 / 60);
    host.clearModelEffects();
    const restored = source.children.length === 0 && source.material === originalMaterial && source.geometry === originalGeometry;
    source.position.x -= 2;
    host.add(new FeatherEffect([source], { count: 300, look: 'gorget', direction: [0, -1, 0] }));
    const deterministic = [...source.children[0].geometry.getAttribute('aRoot').array.slice(0, 30)].every((v, i) => v === initialRoot[i]);
    host.dispose(); originalGeometry.dispose(); originalMaterial.dispose();
    return { atMountIdentity: atMountIdentity || matrixError < 1e-6, attributes, finite, follows, restored, disposed, deterministic };
  });
  assert.ok(Object.values(result).every(Boolean), JSON.stringify(result));
  console.log('PASS source optical attributes, nonuniform transforms, following, deterministic placement, disposal/restoration');
  await page.getByText('渲染组件库', { exact: true }).click();
  await page.locator('[data-experimental] summary').click();
  const target = page.getByLabel('羽毛覆盖对象');
  await target.focus(); await target.selectOption({ label: 'Torus Knot' });
  const card = page.locator('[data-effect=feather]').locator('..');
  await card.locator('select').nth(1).selectOption('gorget');
  await page.locator('[data-effect=feather]').click();
  assert.equal(await page.locator('[data-effect=feather]').getAttribute('aria-pressed'), 'true');
  await page.waitForTimeout(2500);
  await mkdir('smoke-out/effects', { recursive: true });
  await page.screenshot({ path: 'smoke-out/effects/feather-on-model.png', timeout: 60000 });
  await page.locator('[data-effect=feather]').click();
  await page.locator('[data-effect=moss]').click();
  await page.locator('[data-effect=feather]').click();
  assert.equal(await page.locator('[data-effect=moss]').getAttribute('aria-pressed'), 'false');
  await page.getByRole('button', { name: '移除全部组件', exact: true }).click();
  assert.equal(await page.locator('[data-effect][aria-pressed=true]').count(), 0);
  assert.equal(await page.locator('dialog[open]').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS model-target UI, original scene render, growth replacement, remove all; no separate renderer/dialog');
} finally { await browser.close(); }
